#!/usr/bin/env python3
"""
Generate silent stand-ins for libfmod.so.10 / libfmodstudio.so.10.

Why this can work at all: FMOD's C API is opaque handles plus error codes.
Celeste never dereferences a handle itself -- it only passes them back into
FMOD. When the stub *is* FMOD, nothing ever dereferences them, so handing out
an arbitrary non-null token is safe.

It buys a launch, not audio. The point is to answer whether Celeste renders on
Mali-400 and fits in 512 MB, without waiting on an FMOD account. Real sound
needs the genuine armhf libfmod from fmod.com.
"""
import sys

# Functions that must write a handle to an out-parameter, with its argument
# index taken from the public FMOD signature. Return FMOD_OK with a null handle
# here and Celeste's audio init gives up immediately.
HANDLE_OUT = {
    'FMOD_System_Create': 0,
    'FMOD_Studio_System_Create': 0,
    'FMOD_Studio_System_GetCoreSystem': 1,
    'FMOD_Studio_System_GetEvent': 2,
    'FMOD_Studio_System_GetBus': 2,
    'FMOD_Studio_System_GetVCA': 2,
    'FMOD_Studio_System_GetBank': 2,
    'FMOD_Studio_System_LoadBankFile': 3,
    'FMOD_Studio_System_LoadBankMemory': 5,
    'FMOD_Studio_EventDescription_CreateInstance': 1,
    'FMOD_Studio_EventInstance_GetDescription': 1,
    'FMOD_Studio_ParameterInstance_GetDescription': 1,
    'FMOD_System_CreateSound': 4,
    'FMOD_System_CreateStream': 4,
    'FMOD_System_CreateChannelGroup': 2,
    'FMOD_System_CreateSoundGroup': 2,
    'FMOD_System_GetMasterChannelGroup': 1,
    'FMOD_System_GetMasterSoundGroup': 1,
    'FMOD_System_GetChannel': 2,
    'FMOD_System_PlaySound': 4,
    'FMOD_ChannelGroup_GetChannel': 2,
}

# Scalar state getters where a garbage out-value is not harmless: Celeste polls
# these, so a plausible terminal value keeps it from waiting forever.
SCALAR_OUT = {
    # FMOD_STUDIO_LOADING_STATE: LOADED = 3
    'FMOD_Studio_Bank_GetLoadingState':        (1, 3),
    'FMOD_Studio_Bank_GetSampleLoadingState':  (1, 3),
    'FMOD_Studio_EventDescription_GetSampleLoadingState': (1, 3),
    # FMOD_STUDIO_PLAYBACK_STATE: STOPPED = 2, so one-shots are seen to finish
    'FMOD_Studio_EventInstance_GetPlaybackState': (1, 2),
    'FMOD_Studio_Bus_GetPaused':               (1, 0),
    'FMOD_Studio_System_GetParameterByName':   (2, 0),
}

HEADER = '''/* Generated by gen.py -- do not edit. Silent stand-in for %s.
 *
 * Every entry point reports FMOD_OK. Handle-returning calls hand back a token
 * that is never dereferenced, because this library is the only thing that would
 * dereference it. No audio is produced, by design.
 */
#include <stddef.h>

/* One shared token. Its address is all that matters -- never its contents. */
static int fmod_stub_token = 0;
#define TOKEN ((void *) &fmod_stub_token)

'''

def emit(libname, syms):
    out = [HEADER % libname]
    for s in sorted(syms):
        if s in HANDLE_OUT:
            idx = HANDLE_OUT[s]
            args = ', '.join(f'void *a{i}' for i in range(idx + 1))
            out.append(
                f'int {s}({args})\n'
                f'{{\n'
                f'    if (a{idx}) *(void **) a{idx} = TOKEN;\n'
                f'    return 0;\n'
                f'}}\n')
        elif s in SCALAR_OUT:
            idx, val = SCALAR_OUT[s]
            args = ', '.join(f'void *a{i}' for i in range(idx + 1))
            out.append(
                f'int {s}({args})\n'
                f'{{\n'
                f'    if (a{idx}) *(int *) a{idx} = {val};\n'
                f'    return 0;\n'
                f'}}\n')
        else:
            # Unspecified parameter list: the caller passes whatever it likes in
            # registers and on the stack, and ARM EABI leaves the caller to clean
            # up, so ignoring the arguments entirely is safe.
            out.append(f'int {s}() {{ return 0; }}\n')
    return ''.join(out)

syms = [l.strip() for l in open('symbols.txt') if l.strip().startswith('FMOD_')]
studio = [s for s in syms if s.startswith('FMOD_Studio_')]
core   = [s for s in syms if not s.startswith('FMOD_Studio_')]
open('fmod_stub.c','w').write(emit('libfmod.so.10', core))
open('fmodstudio_stub.c','w').write(emit('libfmodstudio.so.10', studio))
print(f'fmod_stub.c:       {len(core)} symbols')
print(f'fmodstudio_stub.c: {len(studio)} symbols')
